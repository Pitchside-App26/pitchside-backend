// Generic fallback that hashes a reg into a believable VW Golf valuation
function hashReg(reg: string): number {
  let h = 0
  for (let i = 0; i < reg.length; i++) {
    h = (h * 31 + reg.charCodeAt(i)) >>> 0
  }
  return h
}

export function getValuation(reg: string): Valuation {
  const clean = reg.replace(/\s/g, '').toUpperCase()
  if (VALUATIONS[clean]) return VALUATIONS[clean]
  const h = hashReg(clean)
  const mileage = 18000 + (h % 30000)
  const dealerOffer = 14800 + (h % 8000)
  const premium = 1800 + (h % 1200)
  return {
    reg: clean.slice(0, 4) + ' ' + clean.slice(4),
    year: 2019 + (h % 4),
    make: 'Volkswagen',
    model: 'Golf',
    trim: ['Match', 'Life', 'R-Line', 'GTI'][h % 4],
    colour: ['Indium Grey', 'Pure White', 'Deep Black', 'Reef Blue'][h % 4],
    mileage,
    dealerOffer,
    privateViaHandover: dealerOffer + premium,
    estimatedLow: dealerOffer + 400,
    estimatedHigh: dealerOffer + premium + 600,
    outstandingFinance: dealerOffer - 4000 + (h % 3000),
    lender: LENDERS[h % LENDERS.length].name,
    financeType: ['pcp', 'hp', 'pcp'][h % 3] as 'pcp' | 'hp',
  }
}

