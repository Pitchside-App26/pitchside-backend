const TIMELINE_STAGES: { stage: DealStage; label: string }[] = [
  { stage: 'listed', label: 'Listed' },
  { stage: 'buyer_found', label: 'Buyer found' },
  { stage: 'funds_in_escrow', label: 'Funds in escrow' },
  { stage: 'lender_contacted', label: 'Lender contacted' },
  { stage: 'settlement_paid', label: 'Settlement paid' },
  { stage: 'v5c_transferred', label: 'V5C transferred' },
  { stage: 'pickup_arranged', label: 'Pickup arranged' },
  { stage: 'released', label: 'Released to buyer' },
]

function buildTimeline(currentStage: DealStage): DealTimelineEvent[] {
  const currentIdx = TIMELINE_STAGES.findIndex(s => s.stage === currentStage)
  return TIMELINE_STAGES.map((s, i) => ({
    stage: s.stage,
    label: s.label,
    completedAt: i < currentIdx ? `May ${i + 1}, 2026` : undefined,
    isCurrent: i === currentIdx,
  }))
}

